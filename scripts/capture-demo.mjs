import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { mkdir } from "node:fs/promises";
const require = createRequire(new URL("../frontend/package.json", import.meta.url));
const { chromium } = require("@playwright/test");
const output = fileURLToPath(new URL("../frontend/test-results/screenshots/", import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || "msedge" });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.goto("http://localhost:3000");
await page.screenshot({ path: `${output}/landing.png`, fullPage: true });
await page.goto("http://localhost:3000/workspace");
await page.getByLabel("Demo account").selectOption("staff-1");
await page.getByRole("button", { name: "Enter demo workspace" }).click();
await page.getByRole("heading", { name: "Registry snapshot", exact: true }).waitFor();
await page.locator(".recharts-bar-rectangle").first().waitFor();
await page.getByRole("button", { name: "Dismiss notification" }).click();
await page.screenshot({ path: `${output}/staff-overview.png`, fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(300);
await page.screenshot({ path: `${output}/mobile-overview.png`, fullPage: true });
console.log(JSON.stringify({ screenshots: output, pageErrors: errors }, null, 2));
await browser.close();
if (errors.length) process.exitCode = 1;